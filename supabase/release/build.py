#!/usr/bin/env python3
"""Builds supabase/release/release-prod.sql: migrations 0007→0011 in ONE transaction (councils 1 Nov 2026).

Paste the generated file into the PRODUCTION SQL editor in one go. Either everything commits or nothing does:
  • a guard refuses to start if social (0007) already exists or the 0001–0006 base is missing;
  • old row counts are recorded first, and a final check raises (→ whole rollback) if any expected object is
    missing or any old table lost rows.
Rehearse first: supabase/release/rehearse.sh (a private Postgres shaped like production, with old data)."""
import pathlib, re
ROOT = pathlib.Path(__file__).resolve().parents[1]
MIG = ["0007_social.sql", "0008_social_v2.sql", "0009_contracts.sql", "0010_hardening.sql", "0011_hardening2.sql", "0012_keep_sent_visible.sql", "0013_employment_contract.sql", "0014_contract_integrity.sql"]
OLD = ["organizations", "profiles", "clients", "projects", "tasks", "task_parts", "messages", "invitations", "attachments"]

head = f"""-- ============================================================================================
-- Hamsha PRODUCTION release — migrations {' → '.join(m[:4] for m in MIG)} in ONE transaction.
-- Generated by supabase/release/build.py — do not edit by hand. Paste ALL of it, run once.
-- Success = «Success. No rows returned» (or the final summary row). Any error = NOTHING was changed.
-- ============================================================================================
begin;
set local lock_timeout = '5s';
set local statement_timeout = '180s';

-- ---------- guard: right database, right moment ----------
do $$ begin
  if to_regclass('public.tasks') is null or to_regclass('public.invitations') is null then
    raise exception 'RELEASE ABORTED: the 0001–0006 base is missing — wrong database?';
  end if;
  if to_regclass('public.posts') is not null then
    raise exception 'RELEASE ABORTED: social (0007) already exists here — this release was applied before';
  end if;
end $$;

-- ---------- old data: counted before, compared after ----------
create temp table release_before on commit drop as
  select * from (values {', '.join(f"('{t}', (select count(*) from {t}))" for t in OLD)}) v(tbl, n);
"""
body = ""
for m in MIG:
    sql = (ROOT / "migrations" / m).read_text(encoding="utf-8")
    if re.search(r"^\s*(commit|rollback)\s*;", sql, re.I | re.M):
        raise SystemExit(f"{m} contains a transaction statement — cannot wrap")
    body += f"\n\n-- ================================ {m} ================================\n{sql}\n"

tail = f"""

-- ---------- final check: anything missing or any old row lost → rollback everything ----------
do $$
declare miss text := '';
begin
  if to_regclass('public.posts') is null then miss := miss || ' posts'; end if;
  if to_regclass('public.post_versions') is null then miss := miss || ' post_versions'; end if;
  if to_regclass('public.client_accounts') is null then miss := miss || ' client_accounts'; end if;
  if to_regclass('public.contracts') is null then miss := miss || ' contracts'; end if;
  if to_regclass('public.contract_versions') is null then miss := miss || ' contract_versions'; end if;
  if to_regclass('public.contract_events') is null then miss := miss || ' contract_events'; end if;
  if to_regclass('public.org_legal') is null then miss := miss || ' org_legal'; end if;
  if to_regclass('public.client_posts') is null then miss := miss || ' client_posts'; end if;
  if to_regclass('public.client_contracts') is null then miss := miss || ' client_contracts'; end if;
  if to_regprocedure('public.can_read_post_media(text)') is null then miss := miss || ' can_read_post_media'; end if;
  if to_regprocedure('public.can_read_attachment(text)') is null then miss := miss || ' can_read_attachment'; end if;
  if to_regprocedure('public.decide_contract(uuid,contract_decision,text,text,text,text)') is null then miss := miss || ' decide_contract'; end if;
  if not exists (select 1 from information_schema.columns where table_name = 'clients' and column_name = 'contract_block') then miss := miss || ' clients.contract_block'; end if;
  if to_regprocedure('public.contract_content_missing(jsonb)') is null then miss := miss || ' contract_content_missing'; end if;
  if not exists (select 1 from information_schema.columns where table_name = 'posts' and column_name = 'published_by') then miss := miss || ' posts.published_by'; end if;
  if not exists (select 1 from pg_enum e join pg_type t on t.oid = e.enumtypid where t.typname = 'contract_kind' and e.enumlabel = 'employment') then miss := miss || ' contract_kind.employment'; end if;
  if miss <> '' then raise exception 'RELEASE ROLLED BACK — missing:%', miss; end if;
  if exists (select 1 from release_before b
             join (values {', '.join(f"('{t}', (select count(*) from {t}))" for t in OLD)}) a(tbl, n) on a.tbl = b.tbl
             where a.n < b.n) then
    raise exception 'RELEASE ROLLED BACK — an old table lost rows';
  end if;
end $$;

select 'Hamsha release 0007–0014 OK' as result,
       (select count(*) from profiles) as profiles, (select count(*) from clients) as clients, (select count(*) from tasks) as tasks;
commit;
"""
out = ROOT / "release" / "release-prod.sql"
out.write_text(head + body + tail, encoding="utf-8")
print(f"wrote {out} ({out.stat().st_size} bytes)")
