"""Builds supabase/release/release-prod-2.sql: migrations 0015 → 0016 in ONE transaction (3 Nov 2026).
Same rules as build.py: a guard (0014 must be there, 0016 must not), old row counts before/after, a final check that
raises (→ whole rollback) on any missing object or lost row. Rehearse first: supabase/release/rehearse2.sh."""
import pathlib, re
ROOT = pathlib.Path(__file__).resolve().parents[1]
MIG = ["0015_trust.sql", "0016_inbox.sql"]
OLD = ["organizations", "profiles", "clients", "projects", "tasks", "task_parts", "messages", "posts", "post_versions", "contracts", "contract_versions"]
head = f"""-- ============================================================================================
-- Hamsha PRODUCTION release 2 — migrations {' → '.join(m[:4] for m in MIG)} in ONE transaction.
-- Generated by supabase/release/build2.py — do not edit by hand. Paste ALL of it, run once.
-- Success = the summary row «Hamsha release 0015–0016 OK». Any error = NOTHING was changed.
-- ============================================================================================
begin;
set local lock_timeout = '5s';
set local statement_timeout = '180s';
do $$ begin
  if to_regprocedure('public.contract_core_missing(jsonb)') is null then
    raise exception 'RELEASE ABORTED: release 1 (0007–0014) is missing — wrong database?';
  end if;
  if to_regclass('public.client_chat_members') is not null then
    raise exception 'RELEASE ABORTED: 0016 already exists here — this release was applied before';
  end if;
end $$;
create temp table release_before on commit drop as
  select * from (values {', '.join(f"('{t}', (select count(*) from {t}))" for t in OLD)}) v(tbl, n);
"""
body = ""
for m in MIG:
    sql = (ROOT / "migrations" / m).read_text(encoding="utf-8")
    if re.search(r"^\s*(commit|rollback|begin)\s*;", sql, re.I | re.M):
        raise SystemExit(f"{m} contains a transaction statement — cannot wrap")
    body += f"\n\n-- ================================ {m} ================================\n{sql}\n"
tail = f"""
do $$
declare miss text := ''; r record; now_n bigint;
begin
  if to_regclass('public.client_chat_members') is null then miss := miss || ' client_chat_members'; end if;
  if to_regclass('public.chat_reads') is null then miss := miss || ' chat_reads'; end if;
  if to_regprocedure('public.inbox_summary()') is null then miss := miss || ' inbox_summary'; end if;
  if to_regprocedure('public.mark_channel_read(uuid)') is null then miss := miss || ' mark_channel_read'; end if;
  if to_regprocedure('public.chat_people(text)') is null then miss := miss || ' chat_people'; end if;
  if to_regprocedure('public.dm_open(text)') is null then miss := miss || ' dm_open'; end if;
  if to_regprocedure('public.is_png_data_url(text)') is null then miss := miss || ' is_png_data_url'; end if;
  if not has_table_privilege('authenticated', 'public.client_chat_members', 'select') then miss := miss || ' grant:client_chat_members'; end if;
  if not has_table_privilege('authenticated', 'public.chat_reads', 'select') then miss := miss || ' grant:chat_reads'; end if;
  if not exists (select 1 from pg_trigger where tgname = 'messages_server_time') then miss := miss || ' messages_server_time'; end if;
  if miss <> '' then raise exception 'RELEASE CHECK FAILED — missing:%', miss; end if;
  for r in select * from release_before loop
    execute format('select count(*) from %I', r.tbl) into now_n;
    if now_n < r.n then raise exception 'RELEASE CHECK FAILED — % lost rows (% → %)', r.tbl, r.n, now_n; end if;
  end loop;
end $$;
select 'Hamsha release 0015–0016 OK' as result, (select count(*) from messages) as messages, (select count(*) from profiles) as profiles;
commit;
"""
(ROOT / "release" / "release-prod-2.sql").write_text(head + body + tail, encoding="utf-8")
print("release-prod-2.sql written")
